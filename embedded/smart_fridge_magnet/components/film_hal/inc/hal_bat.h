/**
 * @brief 初始化电池检测（ADC 单元 + 校准句柄），并立即采样一次。
 */
extern void hal_bat_init(void); 

/**
 * @brief 触发一次 ADC 采样并返回电量百分比（0-100）。
 *
 * 采样期间使能分压电路，返回前关闭以免持续漏电。
 */
extern int hal_bat_get_level(void);

/**
 * @brief 返回上次采样得到的电量百分比（0-100），不触发新采样。
 */
extern int hal_bat_get_percent(void);
/**
 * @brief 获取最近一次采样的电池电压（mV），不触发新的 ADC 采样。
 *
 * 电量百分比由 11 档电压表映射而来、粒度 10%，不足以判断电压升降；
 * 充电状态推断需要 mV 级原始值，故单独提供本接口。
 *
 * @return int 电池电压，单位 mV
 */
extern int hal_bat_get_voltage(void);

/**
 * @brief 释放 ADC 单元与校准句柄，并把 ADC 引脚置为高阻。深睡前调用。
 */
extern void hal_bat_deinit(void);

